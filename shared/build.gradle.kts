val generateMomentumData = tasks.register("generateMomentumData") {
    val exercises = rootProject.file("data/exercises.json")
    val motions = rootProject.file("data/motions.json")
    val strings = rootProject.file("data/i18n/strings.json")
    val exerciseTranslations = rootProject.file("data/i18n/exercises.json")
    val destination = layout.buildDirectory.dir("generated/momentumData/kotlin")
    inputs.file(exercises)
    inputs.file(motions)
    inputs.file(strings)
    inputs.file(exerciseTranslations)
    outputs.dir(destination)
    doLast {
        fun escaped(chunk: String): String = buildString {
            append('"')
            chunk.forEach { c -> append(when (c) {
                '\\' -> "\\\\"
                '"' -> "\\\""
                '$' -> "\\$"
                '\n' -> "\\n"
                '\r' -> "\\r"
                '\t' -> "\\t"
                else -> c.toString()
            }) }
            append('"')
        }
        fun chunks(text: String): String {
            val pieces = mutableListOf<String>()
            var start = 0
            while (start < text.length) {
                var end = (start + 8000).coerceAtMost(text.length)
                if (end < text.length && Character.isHighSurrogate(text[end - 1])) end--
                pieces += escaped(text.substring(start, end))
                start = end
            }
            return pieces.joinToString(",\n        ")
        }
        val file = destination.get().file("com/momentum/model/GeneratedData.kt").asFile
        file.parentFile.mkdirs()
        file.writeText("""// Generated by :shared:generateMomentumData from data/*.json. Do not edit.
package com.momentum.model
internal object GeneratedData {
    val exercisesJson: String = arrayOf(
        ${chunks(exercises.readText())}
    ).joinToString("")
    val motionsJson: String = arrayOf(
        ${chunks(motions.readText())}
    ).joinToString("")
    val stringsJson: String = arrayOf(
        ${chunks(strings.readText())}
    ).joinToString("")
    val exerciseTranslationsJson: String = arrayOf(
        ${chunks(exerciseTranslations.readText())}
    ).joinToString("")
}
""")
    }
}

